import { tokens, type Tokens } from "./tokens.ts";

const kebab = (s: string): string => s.replace(/([a-z])([A-Z0-9])/g, "$1-$2").toLowerCase();
const px = (n: number): string => (n === 0 ? "0" : `${n}px`);

/** Every CSS custom property the design system defines, as [name, value] pairs (name without "--"). */
export function cssVariables(t: Tokens = tokens): Array<[string, string]> {
  const vars: Array<[string, string]> = [];
  const add = (name: string, value: string | number): void => {
    vars.push([name, String(value)]);
  };

  // Core colors keep the names the page already uses (--paper, --ink, --headline...).
  for (const [k, v] of Object.entries(t.color)) add(k === "paper2" ? "paper2" : kebab(k), v);
  add("rule", t.color.ink);
  for (const [k, v] of Object.entries(t.legacyColor)) add(k, v);

  add("display", t.font.display);
  add("mono", t.font.mono);
  // The page reads these three names for its mono text.
  add("ui", t.font.mono);
  add("pixel", t.font.mono);
  add("title", t.font.mono);

  for (const [k, v] of Object.entries(t.fontSize)) add(`text-${k}`, px(v));
  for (const [k, v] of Object.entries(t.displaySize)) add(`display-${k}`, v);
  for (const [k, v] of Object.entries(t.tracking)) add(`tracking-${k}`, v);
  for (const [k, v] of Object.entries(t.space)) add(`space-${k}`, px(v));
  for (const [k, v] of Object.entries(t.radius)) add(`radius-${k}`, v);
  for (const [k, v] of Object.entries(t.border)) add(`border-${k}`, v);
  for (const [k, v] of Object.entries(t.shadow)) add(`shadow-${k}`, v);
  add("max-width", t.layout.maxWidth);
  add("gutter", t.layout.gutter);
  return vars;
}

/** The `:root{...}` block, in the same compact style as guide.html. */
export function rootBlock(t: Tokens = tokens): string {
  const lines = cssVariables(t).map(([n, v]) => `  --${n}:${v};`);
  return [
    "/* tokens:start (generated by design-system/scripts/sync.ts from design-system/src/tokens.ts; edit there) */",
    ":root{",
    "  color-scheme: light;",
    ...lines,
    "}",
    "/* tokens:end */",
  ].join("\n");
}
